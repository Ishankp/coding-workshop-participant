
-- PostgreSQL schema (corrected)
CREATE TYPE user_role AS ENUM (
  'admin',
  'manager',
  'employee'
);

CREATE TABLE users (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email           VARCHAR(255) UNIQUE NOT NULL,
  username        VARCHAR(100) UNIQUE NOT NULL,
  first_name      VARCHAR(100),
  last_name       VARCHAR(100),
  role            user_role NOT NULL DEFAULT 'employee',
  password_hashed VARCHAR(255) NOT NULL          -- was "string", which is not a PostgreSQL type
);

CREATE TABLE projects (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title        VARCHAR(255) NOT NULL,
  start_date   DATE,
  end_date     DATE,
  budget       DECIMAL(14,2) CHECK (budget >= 0),
  archived_at  TIMESTAMP,
  completed_at TIMESTAMP,
  CONSTRAINT projects_dates_chk CHECK (end_date IS NULL OR start_date IS NULL OR end_date >= start_date)
);

CREATE TABLE milestones (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id  INTEGER NOT NULL,
  title       VARCHAR(255) NOT NULL,
  description TEXT,
  start_date  DATE,
  end_date    DATE,
  CONSTRAINT milestones_dates_chk CHECK (end_date IS NULL OR start_date IS NULL OR end_date >= start_date)
);

CREATE TABLE employees (
  id                   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id              INTEGER UNIQUE NOT NULL,
  title                VARCHAR(255),
  salary               DECIMAL(12,2) CHECK (salary >= 0),
  manager_id           INTEGER,
  current_milestone_id INTEGER,
  CONSTRAINT employees_not_own_manager_chk CHECK (manager_id IS NULL OR manager_id <> id)
);

CREATE TABLE employee_projects (
  employee_id INTEGER NOT NULL,
  project_id  INTEGER NOT NULL,
  hours_spent DECIMAL(6,2) NOT NULL DEFAULT 0 CHECK (hours_spent >= 0),
  PRIMARY KEY (employee_id, project_id)          -- replaces the bare unique index; table had no PK
);

-- Foreign keys
ALTER TABLE employees
  ADD CONSTRAINT employees_user_id_fk
  FOREIGN KEY (user_id) REFERENCES users (id)
  ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE;

-- A manager is an employee, so this points at employees, not users
ALTER TABLE employees
  ADD CONSTRAINT employees_manager_id_fk
  FOREIGN KEY (manager_id) REFERENCES employees (id)
  ON DELETE SET NULL DEFERRABLE INITIALLY IMMEDIATE;

ALTER TABLE employees
  ADD CONSTRAINT employees_current_milestone_id_fk
  FOREIGN KEY (current_milestone_id) REFERENCES milestones (id)
  ON DELETE SET NULL DEFERRABLE INITIALLY IMMEDIATE;

ALTER TABLE employee_projects
  ADD CONSTRAINT employee_projects_employee_id_fk
  FOREIGN KEY (employee_id) REFERENCES employees (id)
  ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE;

ALTER TABLE employee_projects
  ADD CONSTRAINT employee_projects_project_id_fk
  FOREIGN KEY (project_id) REFERENCES projects (id)
  ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE;

ALTER TABLE milestones
  ADD CONSTRAINT milestones_project_id_fk
  FOREIGN KEY (project_id) REFERENCES projects (id)
  ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE;

-- PostgreSQL does not index foreign key columns automatically
CREATE INDEX employees_manager_id_idx           ON employees (manager_id);
CREATE INDEX employees_current_milestone_id_idx ON employees (current_milestone_id);
CREATE INDEX employee_projects_project_id_idx   ON employee_projects (project_id);
CREATE INDEX milestones_project_id_idx          ON milestones (project_id);
