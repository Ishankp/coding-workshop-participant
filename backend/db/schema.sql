-- PostgreSQL schema
-- Employees can be assigned to many milestones, within one project or across several,
-- through the employee_milestones join table. Hours are logged per day in time_entries;
-- every hours total in the app is a sum over that log.

CREATE TYPE user_role AS ENUM (
  'admin',
  'manager',
  'employee'
);

CREATE TABLE users (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email           VARCHAR(255) UNIQUE NOT NULL,
  username        VARCHAR(100) UNIQUE NOT NULL,
  first_name      VARCHAR(100),
  last_name       VARCHAR(100),
  role            user_role NOT NULL DEFAULT 'employee',
  password_hashed VARCHAR(255) NOT NULL
);

CREATE TABLE projects (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title        VARCHAR(255) NOT NULL,
  start_date   DATE,
  end_date     DATE,
  budget       DECIMAL(14,2) CHECK (budget >= 0),
  archived_at  TIMESTAMP,
  completed_at TIMESTAMP,
  CONSTRAINT projects_dates_chk CHECK (end_date IS NULL OR start_date IS NULL OR end_date >= start_date)
);

CREATE TABLE milestones (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id   INTEGER NOT NULL,
  title        VARCHAR(255) NOT NULL,
  description  TEXT,
  start_date   DATE,
  end_date     DATE,
  completed_at TIMESTAMP,                      -- set when the milestone is done
  CONSTRAINT milestones_dates_chk CHECK (end_date IS NULL OR start_date IS NULL OR end_date >= start_date)
);

CREATE TABLE employees (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    INTEGER UNIQUE NOT NULL,
  title      VARCHAR(255),
  salary     DECIMAL(12,2) CHECK (salary >= 0),
  manager_id INTEGER,
  CONSTRAINT employees_not_own_manager_chk CHECK (manager_id IS NULL OR manager_id <> id)
);

CREATE TABLE employee_projects (
  employee_id INTEGER NOT NULL,
  project_id  INTEGER NOT NULL,
  PRIMARY KEY (employee_id, project_id)
);

-- One row per (employee, milestone) assignment; replaces employees.current_milestone_id
CREATE TABLE employee_milestones (
  employee_id  INTEGER NOT NULL,
  milestone_id INTEGER NOT NULL,
  PRIMARY KEY (employee_id, milestone_id)    -- an employee can't be assigned to the same milestone twice
);

-- One row per day an employee logs hours on a milestone they're assigned to.
-- created_by_user_id records who entered it: the employee themselves, or a manager/admin on their behalf.
CREATE TABLE time_entries (
  id                 INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id        INTEGER NOT NULL,
  milestone_id       INTEGER NOT NULL,
  work_date          DATE NOT NULL,
  hours              DECIMAL(4,2) NOT NULL CHECK (hours > 0 AND hours <= 24),
  note               VARCHAR(500),
  created_by_user_id INTEGER,
  created_at         TIMESTAMP NOT NULL DEFAULT now()
);

-- Foreign keys
ALTER TABLE employees
ADD CONSTRAINT employees_user_id_fk
FOREIGN KEY (user_id) REFERENCES users (id)
ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE;

-- A manager is an employee, so this points at employees, not users
ALTER TABLE employees
ADD CONSTRAINT employees_manager_id_fk
FOREIGN KEY (manager_id) REFERENCES employees (id)
ON DELETE SET NULL DEFERRABLE INITIALLY IMMEDIATE;

ALTER TABLE employee_projects
ADD CONSTRAINT employee_projects_employee_id_fk
FOREIGN KEY (employee_id) REFERENCES employees (id)
ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE;

ALTER TABLE employee_projects
ADD CONSTRAINT employee_projects_project_id_fk
FOREIGN KEY (project_id) REFERENCES projects (id)
ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE;

ALTER TABLE employee_milestones
ADD CONSTRAINT employee_milestones_employee_id_fk
FOREIGN KEY (employee_id) REFERENCES employees (id)
ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE;

ALTER TABLE employee_milestones
ADD CONSTRAINT employee_milestones_milestone_id_fk
FOREIGN KEY (milestone_id) REFERENCES milestones (id)
ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE;

ALTER TABLE milestones
ADD CONSTRAINT milestones_project_id_fk
FOREIGN KEY (project_id) REFERENCES projects (id)
ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE;

-- Hours can only be logged against an existing milestone assignment
ALTER TABLE time_entries
ADD CONSTRAINT time_entries_assignment_fk
FOREIGN KEY (employee_id, milestone_id) REFERENCES employee_milestones (employee_id, milestone_id)
ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE;

ALTER TABLE time_entries
ADD CONSTRAINT time_entries_created_by_user_id_fk
FOREIGN KEY (created_by_user_id) REFERENCES users (id)
ON DELETE SET NULL DEFERRABLE INITIALLY IMMEDIATE;

-- PostgreSQL does not index foreign key columns automatically.
-- Composite primary keys already cover lookups by their first column
-- (employee_projects.employee_id, employee_milestones.employee_id).
CREATE INDEX employees_manager_id_idx             ON employees (manager_id);
CREATE INDEX employee_projects_project_id_idx     ON employee_projects (project_id);
CREATE INDEX employee_milestones_milestone_id_idx ON employee_milestones (milestone_id);
CREATE INDEX milestones_project_id_idx            ON milestones (project_id);
CREATE INDEX time_entries_assignment_idx         ON time_entries (employee_id, milestone_id);
CREATE INDEX time_entries_milestone_id_idx       ON time_entries (milestone_id);
CREATE INDEX time_entries_employee_date_idx      ON time_entries (employee_id, work_date DESC);